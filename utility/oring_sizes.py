def finer(code):
    """ Look up a Finer Viton code: "MOR28X2V", or "BS214V" (BS series). """
    key = str(code).upper().replace(" ", "")
    try:
        return _FINER_BY_REF[key]
    except KeyError:
        raise KeyError(f"{code!r} is not in the Finer Viton catalogue") from None
